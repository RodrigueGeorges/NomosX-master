#!/usr/bin/env python3
"""Generate lib/brand/athena-field.ts — a luminance matrix of a classical
Athena bust, sampled from a public-domain Wikimedia Commons image.

The matrix drives GodField.tsx: each cell's density becomes the opacity
of a Greek glyph — the goddess rendered in letters.
"""

import io
import urllib.request
from PIL import Image, ImageOps, ImageEnhance

CANDIDATES = [
    "Head of Athena, Roman copy of a Greek original,2nd century C.E., marble.jpg",
    "Head of Athena Getty Villa.jpg",
    "Head Athena Getty Villa 82.AA.79.jpg",
    "Athena_Giustiniani_Musei_Capitolini_MC278.jpg",
]

COLS = 56
ROWS = 72
UA = {"User-Agent": "NomosX-design-tool/1.0 (brand asset generation)"}


def fetch(name: str) -> Image.Image:
    url = (
        "https://commons.wikimedia.org/wiki/Special:FilePath/"
        + urllib.parse.quote(name)
        + "?width=480"
    )
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return Image.open(io.BytesIO(r.read())).convert("L")


def to_matrix(img: Image.Image) -> list[list[int]]:
    img = ImageOps.autocontrast(img, cutoff=2)
    img = ImageEnhance.Contrast(img).enhance(1.35)
    # center-crop toward the top (bust head/torso) then resize
    w, h = img.size
    target = COLS / ROWS
    crop_h = min(h, int(w / target))
    img = img.crop((0, 0, w, crop_h)).resize((COLS, ROWS), Image.LANCZOS)
    px = img.load()
    return [[round(px[c, r] / 255, 2) for c in range(COLS)] for r in range(ROWS)]


def main() -> None:
    img = None
    for name in CANDIDATES:
        try:
            img = fetch(name)
            print(f"using {name}")
            break
        except Exception as e:  # noqa: BLE001
            print(f"skip {name}: {e}")
    if img is None:
        raise SystemExit("no source image could be fetched")

    grid = to_matrix(img)
    flat = ",".join(str(int(v * 100)) for row in grid for v in row)

    out = (
        "/**\n"
        " * Athena — luminance matrix of a classical bust (public domain,\n"
        " * Wikimedia Commons), sampled top-down. Each cell 0-100 becomes\n"
        " * a glyph opacity in GodField — the goddess rendered in letters.\n"
        " * Generated by scripts/greek-god-field.py.\n"
        " */\n"
        f"export const ATHENA_COLS = {COLS};\n"
        f"export const ATHENA_ROWS = {ROWS};\n"
        f"export const ATHENA_FIELD = [{flat}];\n"
    )
    path = "lib/brand/athena-field.ts"
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {path} ({COLS}x{ROWS})")


if __name__ == "__main__":
    main()
