/**
 * EXPORT — Excel workbook & CSV builders for publications
 *
 * Produces analyst-grade deliverables:
 * - XLSX: Report metadata + analysis text + source register + claims + predictions + model results (QUANT BRIDGE)
 * - CSV: source register alone (interoperable with any tooling)
 *
 * Used by /api/articles/[id]/export/data — turns a NomosX publication
 * into a reusable evidence file for tenders and downstream analysis.
 */

import ExcelJS from "exceljs";
import type { ModelResult } from "../quant/types";

export interface ExportSource {
  id: string;
  provider: string;
  title: string;
  year?: number | null;
  doi?: string | null;
  url?: string | null;
  qualityScore?: number | null;
  noveltyScore?: number | null;
  citationCount?: number | null;
  issuer?: string | null;
  documentType?: string | null;
}

export interface ExportClaim {
  text: string;
  claimType: string;
  section: string;
  confidence: number;
  citations: string[];
  hasContradiction: boolean;
  contradictedBy: string[];
}

export interface ExportPrediction {
  claim: string;
  horizon: string;
  probability: number | null;
  confidence: string;
  status: string;
  resolutionCriteria: string;
  createdAt: Date;
  resolvedAt?: Date | null;
  outcome?: string | null;
}

export interface ReportExportData {
  id: string;
  title: string;
  formatLabel: string;
  publishedAt?: Date | null;
  trustScore?: number | null;
  question?: string | null;
  html?: string | null;
  sources: ExportSource[];
  claims?: ExportClaim[];
  predictions?: ExportPrediction[];
  models?: ModelResult[];
}

const HEADER_FILL: ExcelJS.Fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF1A1A2E" } };
const HEADER_FONT: Partial<ExcelJS.Font> = { color: { argb: "FFFFFFFF" }, bold: true };

function styleHeader(row: ExcelJS.Row) {
  row.eachCell((cell) => {
    cell.fill = HEADER_FILL;
    cell.font = HEADER_FONT;
  });
}

/** Strip HTML tags to plain text for Excel inclusion. */
function htmlToText(html: string): string {
  return html
    .replace(/<style[^>]*>[\s\S]*?<\/style>/gi, "")
    .replace(/<script[^>]*>[\s\S]*?<\/script>/gi, "")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/p>/gi, "\n\n")
    .replace(/<\/h[1-6]>/gi, "\n\n")
    .replace(/<li>/gi, "• ")
    .replace(/<\/li>/gi, "\n")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export async function buildReportWorkbook(data: ReportExportData): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = "NomosX";
  wb.created = new Date();

  // ── Sheet 1: Report ──
  const meta = wb.addWorksheet("Report");
  meta.columns = [
    { header: "Field", key: "field", width: 24 },
    { header: "Value", key: "value", width: 90 },
  ];
  styleHeader(meta.getRow(1));
  meta.addRows([
    { field: "Title", value: data.title },
    { field: "Format", value: data.formatLabel },
    { field: "Published", value: data.publishedAt ? data.publishedAt.toISOString().slice(0, 10) : "—" },
    { field: "Trust score", value: data.trustScore ?? "—" },
    { field: "Research question", value: data.question ?? "—" },
    { field: "Source count", value: data.sources.length },
    { field: "Claims", value: data.claims?.length ?? 0 },
    { field: "Predictions", value: data.predictions?.length ?? 0 },
    { field: "Deterministic models", value: data.models?.length ?? 0 },
    { field: "Generated by", value: "NomosX — nomosx.com" },
  ]);

  // ── Sheet 2: Analysis (full text) ──
  if (data.html) {
    const analysis = wb.addWorksheet("Analysis");
    analysis.columns = [{ header: "Full report text", key: "text", width: 120 }];
    styleHeader(analysis.getRow(1));
    const text = htmlToText(data.html);
    // Excel cell limit: 32,767 chars. Split into chunks if needed.
    const CHUNK = 32000;
    for (let i = 0; i < text.length; i += CHUNK) {
      analysis.addRow({ text: text.slice(i, i + CHUNK) });
    }
    analysis.getRow(2).alignment = { wrapText: true, vertical: "top" };
  }

  // ── Sheet 3: Sources ──
  const src = wb.addWorksheet("Sources");
  src.columns = [
    { header: "#", key: "n", width: 5 },
    { header: "Title", key: "title", width: 70 },
    { header: "Provider", key: "provider", width: 16 },
    { header: "Year", key: "year", width: 8 },
    { header: "DOI", key: "doi", width: 30 },
    { header: "URL", key: "url", width: 50 },
    { header: "Quality", key: "quality", width: 9 },
    { header: "Novelty", key: "novelty", width: 9 },
    { header: "Citations", key: "citations", width: 10 },
    { header: "Issuer", key: "issuer", width: 20 },
    { header: "Type", key: "type", width: 14 },
  ];
  styleHeader(src.getRow(1));
  data.sources.forEach((s, i) => {
    src.addRow({
      n: i + 1,
      title: s.title,
      provider: s.provider,
      year: s.year ?? "",
      doi: s.doi ?? "",
      url: s.url ?? "",
      quality: s.qualityScore ?? "",
      novelty: s.noveltyScore ?? "",
      citations: s.citationCount ?? "",
      issuer: s.issuer ?? "",
      type: s.documentType ?? "",
    });
  });
  src.autoFilter = { from: "A1", to: "K1" };

  // ── Sheet 4: Claims ──
  if (data.claims && data.claims.length > 0) {
    const claimsWs = wb.addWorksheet("Claims");
    claimsWs.columns = [
      { header: "Section", key: "section", width: 20 },
      { header: "Type", key: "type", width: 14 },
      { header: "Claim", key: "text", width: 80 },
      { header: "Confidence", key: "confidence", width: 12 },
      { header: "Citations", key: "citations", width: 20 },
      { header: "Contradicted", key: "contradicted", width: 14 },
      { header: "Contradicted by", key: "contradictedBy", width: 30 },
    ];
    styleHeader(claimsWs.getRow(1));
    for (const c of data.claims) {
      claimsWs.addRow({
        section: c.section,
        type: c.claimType,
        text: c.text,
        confidence: `${Math.round(c.confidence * 100)}%`,
        citations: c.citations.join(", "),
        contradicted: c.hasContradiction ? "YES" : "no",
        contradictedBy: c.contradictedBy.join(", "),
      });
    }
    claimsWs.autoFilter = { from: "A1", to: "G1" };
  }

  // ── Sheet 5: Predictions ──
  if (data.predictions && data.predictions.length > 0) {
    const predWs = wb.addWorksheet("Predictions");
    predWs.columns = [
      { header: "Claim", key: "claim", width: 70 },
      { header: "Horizon", key: "horizon", width: 16 },
      { header: "Probability", key: "probability", width: 12 },
      { header: "Confidence", key: "confidence", width: 14 },
      { header: "Status", key: "status", width: 12 },
      { header: "Resolution criteria", key: "criteria", width: 60 },
      { header: "Made", key: "made", width: 12 },
      { header: "Resolved", key: "resolved", width: 12 },
      { header: "Outcome", key: "outcome", width: 50 },
    ];
    styleHeader(predWs.getRow(1));
    for (const p of data.predictions) {
      predWs.addRow({
        claim: p.claim,
        horizon: p.horizon,
        probability: p.probability !== null ? `${Math.round(p.probability * 100)}%` : "—",
        confidence: p.confidence,
        status: p.status,
        criteria: p.resolutionCriteria,
        made: new Date(p.createdAt).toISOString().slice(0, 10),
        resolved: p.resolvedAt ? new Date(p.resolvedAt).toISOString().slice(0, 10) : "—",
        outcome: p.outcome ?? "—",
      });
    }
    predWs.autoFilter = { from: "A1", to: "I1" };
  }

  // ── Sheet 6+: one per deterministic model (QUANT BRIDGE) ──
  for (const model of data.models ?? []) {
    const ws = wb.addWorksheet(`MODEL-${model.modelRef}`.slice(0, 31));
    ws.columns = [
      { header: "Label", key: "label", width: 55 },
      { header: "Value", key: "value", width: 16 },
      { header: "Unit", key: "unit", width: 14 },
      { header: "Low", key: "low", width: 14 },
      { header: "High", key: "high", width: 14 },
      { header: "Note", key: "note", width: 50 },
    ];
    styleHeader(ws.getRow(1));
    for (const r of model.rows) {
      ws.addRow({ label: r.label, value: r.value, unit: r.unit, low: r.low ?? "", high: r.high ?? "", note: r.note ?? "" });
    }
    ws.addRow({});
    ws.addRow({ label: "Model", value: model.name }).font = { bold: true };
    ws.addRow({ label: "Methodology", note: model.methodology });
    ws.addRow({ label: "Data sources", note: model.dataSources.join("; ") });
    for (const p of model.parameters) {
      ws.addRow({ label: `Parameter: ${p.name}`, value: p.value as any, unit: p.unit ?? "", note: p.source });
    }
    for (const c of model.caveats) {
      ws.addRow({ label: "Caveat", note: c });
    }
  }

  const arrayBuffer = await wb.xlsx.writeBuffer();
  return Buffer.from(arrayBuffer as ArrayBuffer);
}

function csvEscape(v: unknown): string {
  const s = String(v ?? "");
  return /[",\n;]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function buildSourcesCSV(data: ReportExportData): string {
  const header = ["n", "title", "provider", "year", "doi", "url", "quality_score", "novelty_score", "citation_count", "issuer", "document_type"];
  const rows = data.sources.map((s, i) => [
    i + 1, s.title, s.provider, s.year ?? "", s.doi ?? "", s.url ?? "",
    s.qualityScore ?? "", s.noveltyScore ?? "", s.citationCount ?? "", s.issuer ?? "", s.documentType ?? "",
  ]);
  return [header, ...rows].map((r) => r.map(csvEscape).join(",")).join("\r\n");
}
